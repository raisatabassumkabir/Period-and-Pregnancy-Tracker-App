/**
 * Colour palettes.
 *
 * Every palette is generated on ONE shared OKLCH lightness scale, so the same
 * step of any role (neutral / accent / accent-2) reads at the same visual value.
 * That is what lets the six palettes swap without re-tuning a single screen.
 *
 * Step numbers keep their ROLE across modes rather than their brightness: the
 * light scale descends and the dark scale ascends, so `bg-neutral-100` is always
 * the base surface tier and `text-neutral-900` is always the highest-contrast
 * ink, in both themes. Pick a step for what it means, never for how bright it
 * happens to look in one mode.
 *
 * Values are space-separated sRGB channels rather than hex so Tailwind's
 * `<alpha-value>` and the `/50` opacity modifiers keep working through the CSS
 * variable indirection. See `tailwind.config.js`.
 *
 * Derived from the Organic design system's ramp curves; `organic.light` holds
 * that system's authored values verbatim so the design canvas matches exactly.
 *
 * Regenerate rather than hand-edit - the curves are the contract, not the hexes.
 */

