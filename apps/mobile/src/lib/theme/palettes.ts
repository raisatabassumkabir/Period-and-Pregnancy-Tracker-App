export function getPaletteTokens(
  id: PaletteId,
  mode: ThemeMode
): PaletteTokens {
  return (PALETTES[id] ?? PALETTES[DEFAULT_PALETTE_ID])[mode];
}

export function isPaletteId(value: unknown): value is PaletteId {
  return (
    typeof value === 'string' &&
    (PALETTE_IDS as readonly string[]).includes(value)
  );
}
